#requires -Version 5.1
# Version checks for the Windows payload, dot-sourced by publish_payload.ps1 and
# tools/run_checks.ps1. Ported from CCSycles' ccycles_version_guard.ps1 (RH-98458).
#
# Windows Installer keeps an installed versioned DLL unless the packaged one is higher, and
# keeps a versioned one over an unversioned one. Between installs of the same component a
# payload DLL that does not go up is silently not installed, so ccycles.dll can end up
# beside another build's DLLs.

# Stamped from Rhino's src4/version.h. ccycles.dll on every build; the oneAPI kernel only
# when its kernels rebuild (src/kernel/device/oneapi/CMakeLists.txt), so it keeps the
# version they were built with. Every other versioned DLL keeps its upstream version.
$CyclesStampedDlls = @('ccycles.dll', 'cycles_kernel_oneapi_jit.dll')
$CyclesRestampedDlls = @('ccycles.dll')
$CyclesPayloadRel = 'RhinoCycles/ccycles/win/release'

# $null for a DLL without a version resource.
function Get-CyclesDllVersion([string]$Path) {
    $i = [System.Diagnostics.FileVersionInfo]::GetVersionInfo($Path)
    $v = [version]::new($i.FileMajorPart, $i.FileMinorPart, $i.FileBuildPart, $i.FilePrivatePart)
    if ($v -eq [version]::new(0, 0, 0, 0)) { return $null }
    return $v
}

# The branch's Rhino version, from the first MajorVersion/MinorVersion in build_dates.msbuild.
function Get-RhinoBranchVersion([string]$RepoRoot) {
    $file = Join-Path $RepoRoot 'build\build_dates.msbuild'
    if (-not (Test-Path -LiteralPath $file)) { return $null }
    $text = Get-Content -LiteralPath $file -Raw
    $major = [regex]::Match($text, '<MajorVersion[^>]*>(\d+)</MajorVersion>')
    $minor = [regex]::Match($text, '<MinorVersion[^>]*>(\d+)</MinorVersion>')
    if (-not $major.Success -or -not $minor.Success) { return $null }
    return [version]::new([int]$major.Groups[1].Value, [int]$minor.Groups[1].Value)
}

# The version ccycles.dll will be stamped with: src4/version.h, generated by Rhino.sln's
# UpdateVersionNumbers and gitignored, so it is whatever branch last built in this folder.
function Get-VersionHeaderVersion([string]$RepoRoot) {
    $file = Join-Path $RepoRoot 'src4\version.h'
    if (-not (Test-Path -LiteralPath $file)) { return $null }
    $m = Select-String -LiteralPath $file -Pattern '#define\s+RMA_VERSION_WITH_PERIODS_STRING\s+"(\d+)\.(\d+)\.(\d+)\.(\d+)"' |
        Select-Object -First 1
    if (-not $m) { return $null }
    $g = $m.Matches[0].Groups
    return [version]::new([int]$g[1].Value, [int]$g[2].Value, [int]$g[3].Value, [int]$g[4].Value)
}

# A file committed in big_libs, from the local LFS store; never fetches. Returns $null when
# nothing is committed at that path, else Oid (sha256) and Object (path, $null if not local).
function Get-CommittedPayloadFile([string]$BigLibsRoot, [string]$Name, [string]$Revision = 'HEAD') {
    # ls-tree, not cat-file -e: nothing on stderr, which Windows PowerShell under Stop throws on.
    if (-not (& git -C $BigLibsRoot ls-tree $Revision -- "$CyclesPayloadRel/$Name")) { return $null }
    $spec = "${Revision}:$CyclesPayloadRel/$Name"

    if ([long](& git -C $BigLibsRoot cat-file -s $spec) -gt 1024) { throw "big_libs $spec is not a Git LFS pointer." }
    $pointer = (& git -C $BigLibsRoot cat-file blob $spec) -join "`n"
    $oid = [regex]::Match($pointer, '(?m)^oid sha256:([0-9a-f]{64})$').Groups[1].Value
    $size = [regex]::Match($pointer, '(?m)^size (\d+)$').Groups[1].Value
    if (-not $oid -or -not $size) { throw "big_libs $spec is not a Git LFS pointer." }

    $gitDir = & git -C $BigLibsRoot rev-parse --path-format=absolute --git-common-dir
    $object = Join-Path $gitDir "lfs/objects/$($oid.Substring(0, 2))/$($oid.Substring(2, 2))/$oid"
    if (-not (Test-Path -LiteralPath $object) -or (Get-Item -LiteralPath $object).Length -ne [long]$size) { $object = $null }
    return [pscustomobject]@{ Name = $Name; Revision = $Revision; Oid = $oid; Object = $object; Size = [long]$size }
}

function Get-NotLocalMessage($Committed) {
    $mb = [Math]::Max(1, [Math]::Round($Committed.Size / 1MB))
    "$($Committed.Name) at big_libs $($Committed.Revision) is not in the local LFS store ($mb MB); " +
    "fetch it with: git -C big_libs lfs fetch origin $($Committed.Revision) --include=`"$CyclesPayloadRel/$($Committed.Name)`""
}

# Before a build: version.h must be this branch's and newer than the committed ccycles.dll,
# or the hour-long build ends in a payload the installer will not install.
function Get-VersionHeaderProblems([string]$RepoRoot, [string]$BigLibsRoot) {
    $hint = 'Build UpdateVersionNumbers in Rhino.sln on this branch to regenerate src4/version.h.'
    $header = Get-VersionHeaderVersion $RepoRoot
    if (-not $header) { return "src4/version.h is missing or has no RMA_VERSION_WITH_PERIODS_STRING. $hint" }

    $branch = Get-RhinoBranchVersion $RepoRoot
    if ($branch -and ($header.Major -ne $branch.Major -or $header.Minor -ne $branch.Minor)) {
        return "src4/version.h is $header, from another branch's build; this branch is $branch. $hint"
    }

    $committed = Get-CommittedPayloadFile $BigLibsRoot 'ccycles.dll'
    if (-not $committed) { return $null }
    if (-not $committed.Object) { return Get-NotLocalMessage $committed }
    $shipped = Get-CyclesDllVersion $committed.Object
    if ($shipped -and $header -eq $shipped) {
        # Developer builds stamp every build of a day 01:00 (build_dates.msbuild).
        return ("src4/version.h is $header, the same as ccycles.dll in big_libs. Either a payload was already " +
                "published today, and every developer build of a day gets the same number, so publish again " +
                "tomorrow; or version.h was not regenerated since that publish. $hint")
    }
    if ($shipped -and $header -lt $shipped) {
        return "src4/version.h is $header, older than ccycles.dll $shipped in big_libs. $hint"
    }
    return $null
}

# Before staging: every top-level DLL that differs from the committed one. Returns
# @{ Problems; Notes }; Notes are not failures.
function Get-PayloadVersionProblems([string]$PayloadDir, [string]$BigLibsRoot, [string]$Revision = 'HEAD', [string]$RepoRoot) {
    $problems = [System.Collections.Generic.List[string]]::new()
    $notes = [System.Collections.Generic.List[string]]::new()
    # -SkipBuild skips the version.h check, so check the stamp itself.
    $branch = if ($RepoRoot) { Get-RhinoBranchVersion $RepoRoot } else { $null }
    foreach ($dll in Get-ChildItem -LiteralPath $PayloadDir -File -Filter '*.dll' | Sort-Object Name) {
        $committed = Get-CommittedPayloadFile $BigLibsRoot $dll.Name $Revision
        if (-not $committed) { continue }
        if ((Get-FileHash -LiteralPath $dll.FullName -Algorithm SHA256).Hash -eq $committed.Oid) { continue }
        if (-not $committed.Object) { $problems.Add((Get-NotLocalMessage $committed)); continue }

        $old = Get-CyclesDllVersion $committed.Object
        $new = Get-CyclesDllVersion $dll.FullName
        if ($branch -and $new -and $CyclesRestampedDlls -contains $dll.Name -and
            ($new.Major -ne $branch.Major -or $new.Minor -ne $branch.Minor)) {
            $problems.Add("$($dll.Name) is $new but this branch is $branch; src4/version.h came from another branch's build")
        }
        if ($old -and -not $new) {
            $problems.Add("$($dll.Name) lost its version (was $old)")
        }
        elseif ($CyclesStampedDlls -contains $dll.Name) {
            if (-not $new -or ($old -and $new -le $old)) {
                $msg = "$($dll.Name) $new is not higher than $old"
                if ($CyclesRestampedDlls -notcontains $dll.Name) {
                    $msg += ". If its kernels did not change, put the committed one back (git -C big_libs restore " +
                            "--source=HEAD --staged --worktree -- $CyclesPayloadRel/$($dll.Name)) and publish again with -SkipBuild"
                }
                $problems.Add($msg)
            }
        }
        elseif ($old -and $new -lt $old) {
            $problems.Add("$($dll.Name) went down from $old to $new")
        }
        elseif ($old -and $new -eq $old) {
            $notes.Add("$($dll.Name) changed but kept version $old; an upgrade keeps the installed copy")
        }
    }
    return [pscustomobject]@{ Problems = $problems; Notes = $notes }
}

# The committed payload, for reverts and merges that nothing re-stamps: ccycles.dll carries
# this branch's version, and stamped DLLs are not lower than the ones they replaced. Returns
# @{ Problems; Notes }; a DLL missing from the local LFS store is a note, not a failure.
function Get-CommittedPayloadVersionProblems([string]$RepoRoot, [string]$BigLibsRoot, [string]$Revision = 'HEAD') {
    $problems = [System.Collections.Generic.List[string]]::new()
    $notes = [System.Collections.Generic.List[string]]::new()
    $branch = Get-RhinoBranchVersion $RepoRoot
    foreach ($name in $CyclesStampedDlls) {
        $committed = Get-CommittedPayloadFile $BigLibsRoot $name $Revision
        if (-not $committed) { continue }
        if (-not $committed.Object) { $notes.Add((Get-NotLocalMessage $committed)); continue }
        $version = Get-CyclesDllVersion $committed.Object
        if (-not $version) { $problems.Add("$name has no version"); continue }
        if ($branch -and $CyclesRestampedDlls -contains $name -and
            ($version.Major -ne $branch.Major -or $version.Minor -ne $branch.Minor)) {
            $problems.Add("$name is $version but this branch is $branch")
        }

        $changedIn = & git -C $BigLibsRoot log --first-parent -n 1 --format=%h $Revision -- "$CyclesPayloadRel/$name"
        if (-not $changedIn) { continue }
        $parent = & git -C $BigLibsRoot rev-parse --short --verify --quiet "$changedIn^1"
        if (-not $parent) {
            # A shallow clone's boundary or the first commit: nothing to compare with.
            $notes.Add("$name was last changed in $changedIn, whose parent is not here (shallow clone?); not compared with the version it replaced")
            continue
        }
        $previous = Get-CommittedPayloadFile $BigLibsRoot $name $parent
        if (-not $previous) { continue }
        if (-not $previous.Object) { $notes.Add((Get-NotLocalMessage $previous)); continue }
        $before = Get-CyclesDllVersion $previous.Object
        if ($before -and $version -le $before) { $problems.Add("$name went from $before to $version in $changedIn") }
    }
    return [pscustomobject]@{ Problems = $problems; Notes = $notes }
}
